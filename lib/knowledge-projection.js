'use strict';

/**
 * Knowledge layer — vault projection.
 *
 * Turns each contact/project's atoms into a regenerated block inside its wiki
 * note (People/<name>.md, Projects/<slug>.md). The note's wiki page becomes a
 * compiled projection of the substrate: claims grouped by predicate, plus a
 * Connections line of [[wikilinks]] derived from real CRM relations, so the
 * graph's edges are rebuilt from knowledge rather than stale manual links.
 *
 * Only the delimited block is ever rewritten — frontmatter, the CRM profile
 * block, hand-written notes and manual links are left untouched. Same sentinel
 * technique already used for the CRM profile block in lib/crm.js.
 */

const db = require('./db');
const { readNote, writeNote } = require('./obsidian-vault');
const { atomsForEntity } = require('./atoms');

const K_START = '<!-- knowledge:start (auto-generated by synthesis — edits here are overwritten) -->';
const K_END = '<!-- knowledge:end -->';

const wl = name => `[[${String(name || '').trim()}]]`;

function buildBlock(atoms, connections) {
  if (!atoms.length && !connections.length) return null;
  const byPred = {};
  for (const a of atoms) (byPred[a.predicate] ||= []).push(a);

  const lines = [
    K_START,
    '## Knowledge',
    '',
    `*Compiled from the knowledge layer — ${atoms.length} claim${atoms.length === 1 ? '' : 's'}, each traceable to its source in the Hub.*`,
    '',
  ];
  for (const pred of Object.keys(byPred)) {
    lines.push(`### ${pred.replace(/_/g, ' ')}`);
    for (const a of byPred[pred]) {
      const conf = Math.round((a.confidence || 0) * 100);
      const flag = a.status === 'proposed' ? ' _(proposed)_' : '';
      lines.push(`- ${a.value} (${conf}%)${flag}`);
    }
    lines.push('');
  }
  if (connections.length) {
    lines.push('## Connections', '', connections.map(wl).join(' · '), '');
  }
  lines.push(K_END);
  return lines.join('\n');
}

function contactConnections(hub, user, contactId) {
  const out = [];
  for (const r of hub.prepare(
    'SELECT co.name FROM contact_companies cc JOIN companies co ON co.id = cc.company_id WHERE cc.contact_id = ?'
  ).all(contactId)) out.push(r.name);
  for (const r of hub.prepare(
    'SELECT p.name FROM contact_projects cp JOIN projects p ON p.id = cp.project_id WHERE cp.contact_id = ?'
  ).all(contactId)) out.push(r.name);
  // Related people via crm_facts.linked_contacts (either direction).
  const linked = new Set();
  for (const f of hub.prepare(
    "SELECT linked_contacts FROM crm_facts WHERE user = ? AND (contact_id = ? OR linked_contacts LIKE ?)"
  ).all(user, contactId, `%${contactId}%`)) {
    try { for (const id of JSON.parse(f.linked_contacts || '[]')) if (id !== contactId) linked.add(id); }
    catch { /* ignore malformed */ }
  }
  for (const id of linked) {
    const c = hub.prepare('SELECT name FROM contacts WHERE id = ?').get(id);
    if (c) out.push(c.name);
  }
  return [...new Set(out)];
}

function projectConnections(hub, projectId) {
  const out = [];
  for (const r of hub.prepare(
    'SELECT c.name FROM contact_projects cp JOIN contacts c ON c.id = cp.contact_id WHERE cp.project_id = ?'
  ).all(projectId)) out.push(r.name);
  for (const r of hub.prepare(
    'SELECT co.name FROM company_projects op JOIN companies co ON co.id = op.company_id WHERE op.project_id = ?'
  ).all(projectId)) out.push(r.name);
  return [...new Set(out)];
}

// Make sure the note exists (create the stub via the existing sync paths), then
// return its current content.
function ensureNote(user, kind, entityId, notePath) {
  const existing = readNote(notePath)?.content;
  if (existing != null) return existing;
  try {
    if (kind === 'contact') {
      require('./crm').syncContactVaultProfile(user, entityId);
    } else if (kind === 'project') {
      const pr = db.hub().prepare('SELECT slug, name FROM projects WHERE id = ?').get(entityId);
      if (pr) require('./wiki-engine').syncProjectNotes([{ ...pr, user }]);
    }
  } catch (_) { /* best effort */ }
  return readNote(notePath)?.content || '';
}

function projectEntity(user, kind, entityId, notePath) {
  const atoms = atomsForEntity(user, kind, entityId, { includeProposed: true });
  if (!atoms.length) return false;
  const hub = db.hub();
  const connections = kind === 'contact'
    ? contactConnections(hub, user, entityId)
    : projectConnections(hub, entityId);
  const block = buildBlock(atoms, connections);
  if (!block) return false;

  const content = ensureNote(user, kind, entityId, notePath);
  const s = content.indexOf(K_START), e = content.indexOf(K_END);
  const updated = (s >= 0 && e > s)
    ? content.slice(0, s) + block + content.slice(e + K_END.length)
    : content.trimEnd() + '\n\n' + block + '\n';
  if (updated === content) return false;

  try {
    writeNote({ notePath, content: updated.trimEnd() + '\n', mode: 'write' });
    return true;
  } catch (err) {
    console.warn(`[knowledge-projection] ${notePath}:`, err.message);
    return false;
  }
}

// Regenerate the knowledge block for every contact/project that has atoms.
function projectAllEntities(user) {
  const hub = db.hub();
  let written = 0;
  const contacts = hub.prepare(`
    SELECT DISTINCT c.id, c.name FROM contacts c
      JOIN knowledge_atoms a ON a.subject_id = c.id AND a.subject_kind = 'contact'
     WHERE c.user = ? AND a.status IN ('active','proposed') AND COALESCE(c.name,'') != ''
  `).all(user);
  for (const c of contacts) {
    if (projectEntity(user, 'contact', c.id, `People/${c.name}.md`)) written++;
  }
  const projects = hub.prepare(`
    SELECT DISTINCT p.id, p.slug FROM projects p
      JOIN knowledge_atoms a ON a.subject_id = p.id AND a.subject_kind = 'project'
     WHERE p.user = ? AND a.status IN ('active','proposed')
       AND p.slug GLOB '[a-z0-9]*'
  `).all(user);
  for (const p of projects) {
    if (projectEntity(user, 'project', p.id, `Projects/${p.slug}.md`)) written++;
  }
  return { written, contacts: contacts.length, projects: projects.length };
}

module.exports = { projectAllEntities, projectEntity, buildBlock };
